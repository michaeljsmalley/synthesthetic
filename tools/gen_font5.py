FIRST, LAST = 32, 90                       # space .. Z: anything else draws as '?'


def columns(rows):
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), rows
    return [sum(1 << y for y in range(7) if rows[y][x] == "#") for x in range(5)]


def header(path):
    out = ["/* generated by tools/gen_font5.py: Synthesthetic's 5 x 7 HUD font, ' ' .. 'Z', a byte a column, bit 0 the",
           " * top row; a character without a glyph is drawn as '?' */", "#pragma once", "#include <stdint.h>",
           f"#define VFONT5_FIRST {FIRST}", f"#define VFONT5_LAST {LAST}",
           f"static const uint8_t VFONT5[{LAST - FIRST + 1}][5] = {{"]
    for c in range(FIRST, LAST + 1):
        g = GLYPHS.get(chr(c), GLYPHS["?"])
        out.append("    {" + ", ".join(str(v) for v in columns(g)) + "},   /* " + (chr(c) if chr(c) != "\\" else "bs") + " */")
    out.append("};")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"font5: {LAST - FIRST + 1} glyphs -> {path}")


def sheet(path):
    from PIL import Image
    chars = [chr(c) for c in range(FIRST, LAST + 1)]
    S, per = 6, 20
    rows = (len(chars) + per - 1) // per
    im = Image.new("RGB", (per * 6 * S + 8, rows * 9 * S + 8), (20, 20, 24))
    px = im.load()
    for i, ch in enumerate(chars):
        g = GLYPHS.get(ch, GLYPHS["?"])
        ox, oy = 4 + (i % per) * 6 * S, 4 + (i // per) * 9 * S
        for y in range(7):
            for x in range(5):
                if g[y][x] == "#":
                    for a in range(S):
                        for b in range(S):
                            px[ox + x * S + a, oy + y * S + b] = (240, 240, 240)
    im.save(path)
    print("font5: sheet ->", path)


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--sheet":
        sheet(sys.argv[2])
    else:
        header(sys.argv[1] if len(sys.argv) > 1 else "build/gen/vfont5.h")
