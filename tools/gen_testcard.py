"""The still frame while the video core is off: a 320 x 180 test card as a baseline JPEG (4:2:0, quality 80),
emitted as a const array for the firmware (flash, XIP). Colour bars, a grey ramp, a circle and the name, so
a host's camera app shows at a glance that the stream, its size and its colours are right.

  gen_testcard.py build/gen/uvc_testcard.h
"""
import io
import sys

from PIL import Image, ImageDraw


def card():
    im = Image.new("RGB", (320, 180), (12, 12, 20))
    d = ImageDraw.Draw(im)
    bars = [(255, 255, 255), (255, 255, 0), (0, 255, 255), (0, 255, 0), (255, 0, 255), (255, 0, 0), (0, 0, 255), (16, 16, 16)]
    for i, c in enumerate(bars):
        d.rectangle((i * 40, 0, i * 40 + 39, 69), fill=c)
    for x in range(320):
        v = x * 255 // 319
        d.line((x, 74, x, 94), fill=(v, v, v))
    d.ellipse((220, 100, 300, 176), outline=(255, 255, 255), width=3)
    d.ellipse((250, 128, 270, 148), fill=(255, 120, 40))
    d.rectangle((0, 0, 319, 179), outline=(255, 255, 255), width=1)
    d.text((8, 104), "FM-1DROME  VIDEO CORE OFF", fill=(255, 255, 255))
    d.text((8, 118), "320x180 MJPEG", fill=(180, 220, 255))
    d.text((8, 132), "TEST CARD", fill=(255, 200, 120))
    return im


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "build/gen/uvc_testcard.h"
    buf = io.BytesIO()
    card().save(buf, "JPEG", quality=80, subsampling="4:2:0", optimize=False)
    data = buf.getvalue()
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    with open(out, "w") as f:
        f.write("/* SPDX-License-Identifier: GPL-3.0-only */\n")
        f.write(f"/* generated by tools/gen_testcard.py: a 240 x 240 baseline JPEG test card, {len(data)} bytes */\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write(f"#define UVC_TESTCARD_LEN {len(data)}u\n")
        f.write(f"static const uint8_t UVC_TESTCARD[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n")
    print(f"test card: 320x180 JPEG, {len(data)} B -> {out}")


if __name__ == "__main__":
    main()
