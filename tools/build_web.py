"""Compile Synthesthetic for the browser: the firmware's sources with firmware/host/web.c (the browser's HAL) to
WebAssembly, for the Play page (web/play/). No JieLi SDK, Docker or FM-1 needed: Emscripten (brew install emscripten),
or clang with wasm-ld.

  python3 tools/build_web.py [--release 0.1]      -> build/web/synthesthetic.wasm
  python3 tools/build_web.py --song tools/songs/x.py --out build/x.wasm     another song for the first visit
"""
import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "build/gen"
OUT = ROOT / "build/web"
SONG = ROOT / "tools/songs/demo.py"                 # the Play page's song
sys.path.insert(0, str(ROOT / "tools"))


def web_hal():
    """the HAL's tables web.c shares (build/gen/web_hal.h): FM1_KEYMAP (hal/fm1_input.h), the flash map (fm1_flash.h)"""
    keys = (ROOT / "firmware/hal/fm1_input.h").read_text()
    m = re.search(r"static const int8_t FM1_KEYMAP\[6\]\[FM1_NCOL\] = \{.*?\n\};", keys, re.S)
    # the flash map is per board since the SMK-37 layer (hal/fm1_flash_map.h): FL_IN from its common part, the
    # windows and FL_STORE_OK from its FM-1 half (the browser's FM-1 keeps the FM-1's layout)
    fmap = (ROOT / "firmware/hal/fm1_flash_map.h").read_text()
    fm1 = fmap[fmap.index("#else /* FM-1 */"):]
    flash = re.findall(r"^#define FL_IN\(.*?(?<!\\)$", fmap, re.M | re.S) + \
        re.findall(r"^#define FL_(?:(?:DATA|GLOB|OTA|FM6|USR4)_(?:LO|HI)\b|STORE_OK\().*?(?<!\\)$", fm1, re.M | re.S)
    if not m or len(flash) != 12:
        raise SystemExit(f"build_web: FM1_KEYMAP or the flash map not found in firmware/hal/ ({len(flash)} of 12 flash lines)")
    (GEN / "web_hal.h").write_text("/* generated by tools/build_web.py from firmware/hal/fm1_input.h and fm1_flash_map.h */\n"
                                   "#pragma once\n" + m.group(0) + "\n" + "\n".join(flash) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--release", help="the version the boot screen shows (as tools/build.py --release)")
    ap.add_argument("--out", default=str(OUT / "synthesthetic.wasm"), help="where (the tests build their own)")
    ap.add_argument("--song", default=str(SONG), help="the first visit's song (tools/songs/, tools/songlib.py)")
    a = ap.parse_args()
    import build
    build.generate()
    web_hal()
    OUT.mkdir(parents=True, exist_ok=True)
    flags = ["-O2", "-fwrapv", "-fno-strict-aliasing", "-Wno-unused-function", "-Wno-unused-variable",
             "-Wno-unknown-attributes", "-Wno-ignored-attributes", "-I" + str(GEN), "-I" + str(ROOT / "firmware/src")]
    if a.release:
        v = a.release.upper()
        flags.append('-DFELUCCA_VERSION="SYNTHESTHETIC ' + (v if "BETA" in v else v + " BETA") + '"')
    wasm = Path(a.out).resolve()
    wasm.parent.mkdir(parents=True, exist_ok=True)
    song_h = wasm.with_suffix(".song.h")            # (the song's tables, next to what they build)
    subprocess.run([sys.executable, str(Path(a.song).resolve()), "--header", str(song_h), "--json",
                    str(wasm.with_suffix(".song.json")), "--quiet"], cwd=ROOT, check=True)
    flags.append(f'-DWEB_SONG_H="{song_h}"')
    src = str(ROOT / "firmware/host/web.c")
    if shutil.which("emcc"):
        cmd = ["emcc", src, *flags, "--no-entry", "-sSTANDALONE_WASM=1", "-sFILESYSTEM=0", "-sINITIAL_MEMORY=33554432",
               "-sSTACK_SIZE=262144", "-sALLOW_MEMORY_GROWTH=0", "-sERROR_ON_UNDEFINED_SYMBOLS=1", "-o", str(wasm)]
    elif shutil.which("clang") and shutil.which("wasm-ld"):
        shim = ROOT / "tools/wasm_shim"
        mem = wasm.parent / "mem.o"
        subprocess.run(["clang", "--target=wasm32", "-O2", "-fno-builtin", "-ffreestanding", "-c", str(shim / "mem.c"),
                        "-o", str(mem)], check=True)
        cmd = ["clang", "--target=wasm32", *flags, "-ffreestanding", "-nostdlib", "-I" + str(shim), src, str(mem),
               "-Wl,--no-entry", "-Wl,--export-memory", "-Wl,--initial-memory=33554432", "-Wl,-z,stack-size=262144",
               "-o", str(wasm)]
    else:
        raise SystemExit("Install Emscripten (macOS: brew install emscripten), or clang and lld (wasm-ld).")
    subprocess.run(cmd, cwd=ROOT, check=True)
    print(f"Synthesthetic for the browser: {wasm} ({wasm.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
