"""The Synthesthetic logo: a ring of the twelve chromatic hues (the twelve tones) around a dark centre, with a
white wave through it.

  tools/gen_logo.py OUT.h          the firmware's boot splash icon (RLE, 16-colour palette, RGB565)
  tools/gen_logo.py --assets DIR   synthesthetic-icon.png / .svg, synthesthetic-logo.png (the icon and the name)
"""
import colorsys
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw

BLACK, WHITE, GREY = (0, 0, 0), (242, 242, 242), (110, 110, 118)
HUES = [tuple(round(v * 255) for v in colorsys.hsv_to_rgb(i / 12, 0.92, 1.0)) for i in range(12)]
ICON = 112                                        # the splash icon's side


def draw_icon(size, ss=4, wave=True):
    """the icon at size x size, drawn ss times larger and shrunk (anti-aliased); the firmware draws its own wave"""
    S = size * ss
    im = Image.new("RGB", (S, S), BLACK)
    d = ImageDraw.Draw(im)
    c = S / 2
    R, r = S * 0.48, S * 0.31
    for i, col in enumerate(HUES):
        a0 = -90 + i * 30 - 180 / 12 * 0.08
        d.pieslice((c - R, c - R, c + R, c + R), a0, a0 + 30, fill=col)
    d.ellipse((c - r, c - r, c + r, c + r), fill=BLACK)
    if wave:
        pts = []
        n = 64
        for k in range(n + 1):
            x = c - r * 0.82 + (2 * r * 0.82) * k / n
            pts.append((x, c - r * 0.42 * math.sin(2 * math.pi * k / n)))
        d.line(pts, fill=WHITE, width=max(2, S // 28), joint="curve")
    return im.resize((size, size), Image.LANCZOS)


def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def splash_header(path):
    im = draw_icon(ICON, wave=False)
    cols = [BLACK, WHITE, GREY] + HUES + [tuple(v // 2 for v in WHITE)]
    src = im.tobytes()
    px, cache = [], {}
    for i in range(0, len(src), 3):
        p = (src[i], src[i + 1], src[i + 2])
        if p not in cache:
            cache[p] = min(range(16), key=lambda k: sum((p[j] - cols[k][j]) ** 2 for j in range(3)))
        px.append(cache[p])
    rle = bytearray()                                 # (run - 1) << 4 | index, runs of 1..16
    i = 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == px[i] and j - i < 16:
            j += 1
        rle.append(((j - i - 1) << 4) | px[i])
        i = j
    L = ["/* generated by tools/gen_logo.py: the Synthesthetic boot splash icon */", "#pragma once", "#include <stdint.h>",
         f"#define LOGO_W {ICON}", f"#define LOGO_H {ICON}",
         "static const uint16_t LOGO_PAL[16] = {" + ", ".join(str(rgb565(c)) for c in cols) + "};",
         f"static const uint8_t LOGO_RLE[{len(rle)}] = {{"]
    for k in range(0, len(rle), 24):
        L.append("    " + ", ".join(str(b) for b in rle[k:k + 24]) + ",")
    L.append("};")
    Path(path).write_text("\n".join(L) + "\n")
    print(f"logo: icon {ICON}x{ICON}, {len(rle)} B RLE -> {path}")


def svg_icon(size=200):
    c, R, r = size / 2, size * 0.48, size * 0.31
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}">']
    for i, col in enumerate(HUES):
        a0, a1 = math.radians(-90 + i * 30), math.radians(-90 + i * 30 + 30)
        x0, y0, x1, y1 = c + R * math.cos(a0), c + R * math.sin(a0), c + R * math.cos(a1), c + R * math.sin(a1)
        parts.append(f'<path d="M{c:.1f},{c:.1f} L{x0:.1f},{y0:.1f} A{R:.1f},{R:.1f} 0 0 1 {x1:.1f},{y1:.1f} Z" fill="#%02X%02X%02X"/>' % col)
    parts.append(f'<circle cx="{c}" cy="{c}" r="{r:.1f}" fill="#000"/>')
    pts = " ".join(f"{c - r * 0.82 + 2 * r * 0.82 * k / 32:.1f},{c - r * 0.42 * math.sin(2 * math.pi * k / 32):.1f}" for k in range(33))
    parts.append(f'<polyline points="{pts}" fill="none" stroke="#F2F2F2" stroke-width="{size / 28:.1f}" stroke-linejoin="round" stroke-linecap="round"/>')
    parts.append("</svg>")
    return "\n".join(parts)


ROYGBIV = ["#FF2020", "#FF8C14", "#FFEB14", "#28FF46", "#148CFF", "#4B0082", "#8F00FF"]


def svg_logo(animated=True):
    """the icon and the name: each letter a colour of the spectrum, every letter fading to the next (SMIL)"""
    letters = "SYNTHESTHETIC"
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1180 240" width="1180" height="240">',
             '<rect width="1180" height="240" fill="#000"/>',
             '<g transform="translate(20,20)">' + svg_icon(200).split(">", 1)[1].rsplit("</svg>", 1)[0] + "</g>"]
    cycle = ROYGBIV + [ROYGBIV[0]]
    for i, ch in enumerate(letters):
        x = 250 + i * 70
        col = ROYGBIV[(i * 7) // 13]
        anim = ""
        if animated:
            vals = ";".join(cycle[(k + (i * 7) // 13) % 7] for k in range(8))
            anim = f'<animate attributeName="fill" values="{vals}" dur="4s" repeatCount="indefinite"/>'
        parts.append(f'<text x="{x}" y="160" font-family="Menlo, Consolas, monospace" font-size="92" font-weight="700" fill="{col}">{ch}{anim}</text>')
    parts.append("</svg>")
    return "\n".join(parts)


def web_icons(out):
    """the PWA icons: 192, 512, and a maskable 512 (the ring inside the safe zone)"""
    out = Path(out)
    draw_icon(192).save(out / "icon-192.png")
    draw_icon(512).save(out / "icon-512.png")
    m = Image.new("RGB", (512, 512), BLACK)
    m.paste(draw_icon(400), (56, 56))
    m.save(out / "icon-maskable-512.png")
    print(f"logo: web icons in {out}")


def assets(out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    draw_icon(512).save(out / "synthesthetic-icon.png")
    (out / "synthesthetic-icon.svg").write_text(svg_icon())
    (out / "synthesthetic-logo.svg").write_text(svg_logo())
    logo = Image.new("RGB", (1180, 240), BLACK)
    logo.paste(draw_icon(200), (20, 20))
    d = ImageDraw.Draw(logo)
    try:
        from PIL import ImageFont
        font = ImageFont.truetype("/System/Library/Fonts/Menlo.ttc", 84, index=1)   # Menlo Bold on macOS
    except Exception:
        font = None
    for i, ch in enumerate("SYNTHESTHETIC"):
        d.text((250 + i * 70, 70), ch, fill=ROYGBIV[(i * 7) // 13], font=font)
    logo.save(out / "synthesthetic-logo.png")
    print(f"logo: assets in {out}")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--assets":
        assets(sys.argv[2])
    elif len(sys.argv) == 3 and sys.argv[1] == "--web":
        web_icons(sys.argv[2])
    else:
        splash_header(sys.argv[1] if len(sys.argv) > 1 else "build/gen/synthesthetic_logo.h")
