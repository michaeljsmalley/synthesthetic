"""SCREEN mode's colours: the 256-colour palette of the display's copy (firmware/src/mirror.c) and the table that
picks a palette entry for a display colour.
    tools/gen_mirror.py build/gen/vmirror.h
The palette: a 6 x 6 x 6 cube (0, 51 .. 255 a channel; index 36 r + 6 g + b) and a ramp of 40 greys (216..255),
so the interface's greys and its theme colours both land close. MIR_IDX: a display colour (RGB565, as the LCD
gets it) by its top 4 bits a channel (RGB 4-4-4, 4096 entries) -> the nearest palette entry, measured with the
channels weighted 3 4 2 (green counts most, as the eye has it); the bin's lowest colour stands for
it (its highest in the top bin), so black and white stay exact. MIR_LUM: each
entry's brightness (JFIF Y), for the shared pixels' stronger-one test."""
import sys

LEVELS = [0, 51, 102, 153, 204, 255]
GREYS = [round(k * 255 / 39) for k in range(40)]


def palette():
    pal = [(r, g, b) for r in LEVELS for g in LEVELS for b in LEVELS]
    pal += [(v, v, v) for v in GREYS]
    assert len(pal) == 256
    return pal


def nearest(pal, c):
    r, g, b = c
    best, bi = None, 0
    for i, (pr, pg, pb) in enumerate(pal):
        d = 3 * (pr - r) ** 2 + 4 * (pg - g) ** 2 + 2 * (pb - b) ** 2
        if best is None or d < best:
            best, bi = d, i
    return bi


def main(out):
    pal = palette()
    idx = []
    for r4 in range(16):
        for g4 in range(16):
            for b4 in range(16):
                # the bin's lowest colour (black stays black), its highest in the top bin (white stays white):
                # RGB565 r5 in {2 r4, 2 r4 + 1}, g6 in {4 g4 .. 4 g4 + 3}, b5 like r5, expanded to 8 bits
                r = (2 * r4 + (r4 == 15)) * 255 / 31
                g = (4 * g4 + 3 * (g4 == 15)) * 255 / 63
                b = (2 * b4 + (b4 == 15)) * 255 / 31
                idx.append(nearest(pal, (r, g, b)))
    lum = [(77 * r + 150 * g + 29 * b + 128) >> 8 for r, g, b in pal]
    with open(out, "w") as f:
        f.write("/* generated by tools/gen_mirror.py: SCREEN mode's palette (firmware/src/mirror.c) */\n#pragma once\n")
        f.write("static const uint8_t MIR_IDX[4096] = {\n")
        for k in range(0, 4096, 32):
            f.write("    " + ", ".join(str(v) for v in idx[k:k + 32]) + ",\n")
        f.write("};\nstatic const uint8_t MIR_RGB[256][3] = {\n")
        for k in range(0, 256, 8):
            f.write("    " + ", ".join("{%d, %d, %d}" % c for c in pal[k:k + 8]) + ",\n")
        f.write("};\nstatic const uint8_t MIR_LUM[256] = {\n")
        for k in range(0, 256, 32):
            f.write("    " + ", ".join(str(v) for v in lum[k:k + 32]) + ",\n")
        f.write("};\n")
    print(f"gen_mirror: {out}: 4096 + 768 + 256 B")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/gen/vmirror.h")
